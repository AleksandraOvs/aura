    <h2 id="file-preparation">3. Подготовка файла поставщика</h2>

    <h3>3.1 CSV</h3>

    <p>
        Для CSV текущий импортёр использует разделитель
        <code>;</code>.
    </p>

    <p>
        Первая строка файла должна содержать названия колонок.
        Именно по этим названиям конфигурация поставщика
        обращается к данным.
    </p>

    <p>
        Пример:
    </p>

    <pre>
Артикул;Название;Цена;Бренд;Фото
DK5010-BK;Бра Denkirs DK5010-BK;10000;Denkirs;https://example.com/image.jpg
    </pre>

    <h3>3.2 Важные правила CSV</h3>

    <ul>
        <li>Разделитель — <code>;</code>.</li>
        <li>Первая строка — заголовки.</li>
        <li>Названия колонок должны соответствовать конфигурации.</li>
        <li>Пустые строки игнорируются.</li>
        <li>Лишние значения в строке не используются.</li>
        <li>Недостающие значения становятся пустыми.</li>
        <li>BOM в начале файла обрабатывается.</li>
    </ul>

    <h3>3.3 Дублирующиеся заголовки</h3>

    <p>
        Если поставщик прислал несколько одинаковых колонок,
        парсер автоматически добавляет суффикс.
    </p>

    <pre>
Артикул
Артикул_2
Артикул_3
    </pre>

    <p>
        Это важно учитывать при создании конфигурации.
        Например, если нужный артикул находится в первой колонке,
        используется <code>Артикул</code>.
    </p>


    <h3>3.4 XML / YML</h3>

    <p>
        XML/YML-файлы обрабатываются через
        <code>YmlParser</code>.
    </p>

    <p>
        Обычно товар находится внутри элемента
        <code>&lt;offer&gt;</code>.
    </p>

    <p>
        Например:
    </p>

    <pre>
&lt;offer id="123"&gt;
    &lt;name&gt;Товар&lt;/name&gt;
    &lt;vendor&gt;Maytoni&lt;/vendor&gt;
    &lt;price&gt;10000&lt;/price&gt;
    &lt;picture&gt;https://example.com/image.jpg&lt;/picture&gt;
&lt;/offer&gt;
    </pre>

    <p>
        Повторяющиеся элементы сохраняются как массивы.
    </p>

    <p>
        Элементы
        <code>&lt;param name="..."&gt;</code>
        преобразуются в структуру:
    </p>

    <pre>
param.Название параметра
    </pre>


