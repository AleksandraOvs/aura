[
    'supplier' => '',
    'external_id' => '',
    'sku' => '',
    'barcode' => '',
    'name' => '',
    'description' => '',
    'short_description' => '',
    'price' => 0,
    'old_price' => null,
    'stock' => null,
    'available' => true,
    'brand' => '',
    'categories' => [],
    'images' => [],
    'videos' => [],
    'documents' => [],
    'attributes' => [],
    'meta' => [],
    'source_url' => '',
    'currency' => '',
]
    </pre>

    <p>
        Это центральная точка всей архитектуры.
        WooCommerce не должен знать, как именно поставщик
        называл свои поля.
    </p>


