    <!-- =====================================================
         22. ТИПОВЫЕ ПРОБЛЕМЫ
    ====================================================== -->

    <hr>

    <h2 id="problems">22. Типовые проблемы</h2>


    <h3>Товар создаётся повторно</h3>

    <p>
        Проверить:
    </p>

    <pre>
supplier
external_id
    </pre>

    <p>
        Они должны быть стабильными между импортами.
    </p>


    <h3>Не создаётся изображение</h3>

    <p>
        Проверить:
    </p>

    <ul>
        <li>URL изображения;</li>
        <li>доступность URL;</li>
        <li>результат normalized product;</li>
        <li>значение <code>failed</code> в image_import.</li>
    </ul>


    <h3>Нет атрибута у товара</h3>

    <p>
        Проверить:
    </p>

    <ol>
        <li>есть ли атрибут в normalized product;</li>
        <li>есть ли соответствие в AttributeMapper;</li>
        <li>существует ли taxonomy <code>pa_...</code>;</li>
        <li>есть ли term у товара.</li>
    </ol>


    <h3>Цена не обновилась</h3>

    <p>
        Проверить:
    </p>

    <pre>
price !== null
    </pre>

    <p>
        Если поставщик не передал цену,
        текущая цена намеренно не изменяется.
    </p>


