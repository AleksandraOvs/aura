    <h2 id="import-scheme">2. Общая схема импорта</h2>

    <ol>
        <li>Получить файл поставщика.</li>
        <li>Проверить формат и структуру файла.</li>
        <li>Положить файл в папку соответствующего поставщика.</li>
        <li>Создать или проверить конфигурацию поставщика.</li>
        <li>Парсер читает файл.</li>
        <li>ProductNormalizer приводит данные к единому формату.</li>
        <li>ProductImporter ищет существующий товар.</li>
        <li>Если товара нет — создаётся новый.</li>
        <li>Если товар есть — обновляется существующий.</li>
        <li>Обрабатываются категории.</li>
        <li>Обрабатываются глобальные атрибуты.</li>
        <li>Загружаются изображения.</li>
        <li>Сохраняются supplier meta.</li>
    </ol>


