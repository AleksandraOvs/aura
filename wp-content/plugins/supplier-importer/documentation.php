    <h2 id="product-update">8. Создание и обновление товара</h2>

    <p>
        Если товар не найден:
    </p>

    <pre>
new WC_Product_Simple()
    </pre>

    <p>
        Если найден:
    </p>

    <pre>
wc_get_product($product_id)
    </pre>

    <p>
        Затем применяются переданные значения.
    </p>

    <p>
        Важный принцип:
        отсутствие значения у поставщика не должно автоматически
        превращаться в ноль или пустое значение.
    </p>


