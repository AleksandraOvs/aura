    <h2 id="product-identification">7. Как определяется существующий товар</h2>

    <p>
        Главный принцип идентификации:
    </p>

    <pre>
supplier + external_id
    </pre>

    <p>
        Например:
    </p>

    <pre>
supplier = maytoni
external_id = FR6224PL-L6AM2
    </pre>

    <p>
        По этим двум значениям импортёр ищет существующий
        WooCommerce product.
    </p>

    <p>
        Поэтому повторный импорт одного и того же товара
        не создаёт новый товар.
    </p>

    <p>
        Пример:
    </p>

    <pre>
Первый импорт:
FR6224PL-L6AM2 → ID 596 → создан

Второй импорт:
FR6224PL-L6AM2 → ID 596 → обновлён
    </pre>


