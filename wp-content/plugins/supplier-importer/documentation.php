    <h2 id="price">9. Цена</h2>

    <p>
        Если <code>price</code> передан и не равен
        <code>null</code>, он устанавливается как
        regular price WooCommerce.
    </p>

    <pre>
price → regular_price
    </pre>

    <p>
        Если цена отсутствует:
    </p>

    <pre>
price = null
    </pre>

    <p>
        текущая цена товара не изменяется.
    </p>

    <h3>Старая цена</h3>

    <p>
        <code>old_price</code> пока сохраняется отдельно:
    </p>

    <pre>
_supplier_old_price
    </pre>

    <p>
        Это намеренно сделано отдельно от окончательной
        ценовой политики магазина.
    </p>


