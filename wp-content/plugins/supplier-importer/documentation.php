    <h2 id="stock">10. Остаток и наличие</h2>

    <p>
        Если поставщик передал числовой <code>stock</code>,
        импортёр включает управление остатками:
    </p>

    <pre>
stock > 0 → instock
stock = 0 → outofstock
    </pre>

    <p>
        Если:
    </p>

    <pre>
stock = null
    </pre>

    <p>
        остаток существующего товара не изменяется.
    </p>

    <div class="notice notice-warning inline">
        <p>
            <strong>Важно:</strong>
            поле available пока не используется как самостоятельная
            логика определения наличия. У разных поставщиков
            available и stock могут противоречить друг другу.
        </p>
    </div>


