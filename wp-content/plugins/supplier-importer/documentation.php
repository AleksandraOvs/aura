    <h2 id="attributes">12. Глобальные атрибуты</h2>

    <p>
        Атрибуты поставщика сначала получают нормализованное имя:
    </p>

    <pre>
power
voltage
collection
color_temperature
...
    </pre>

    <p>
        Затем <code>AttributeMapper</code> определяет,
        какому глобальному атрибуту WooCommerce соответствует
        это поле.
    </p>

    <p>
        Например:
    </p>

    <pre>
power
    ↓
pa_moshhnost-w

voltage
    ↓
pa_napryazhenie

collection
    ↓
pa_collection
    </pre>

    <h3>Если глобального атрибута нет</h3>

    <p>
        Импортёр может создать его автоматически,
        если соответствие предусмотрено в AttributeMapper.
    </p>

    <h3>Значения атрибутов</h3>

    <p>
        Если term существует — он используется.
        Если нет — term создаётся.
    </p>

    <p>
        При обновлении конкретного атрибута его старые значения
        заменяются новыми.
    </p>

    <pre>
Было:
Мощность = 10

Поставщик прислал:
Мощность = 12

После импорта:
Мощность = 12
    </pre>

    <p>
        Другие атрибуты товара при этом не удаляются.
    </p>


