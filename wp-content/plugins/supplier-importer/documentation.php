    <h2 id="purpose">1. Назначение плагина</h2>

    <p>
        Supplier Importer предназначен для универсальной загрузки
        товаров разных поставщиков в WooCommerce.
    </p>

    <p>
        Поставщики могут использовать разные форматы файлов,
        разные названия полей и разные структуры данных.
        Поэтому импорт не работает напрямую с WooCommerce.
        Сначала данные приводятся к единой внутренней структуре.
    </p>

    <p>
        Основная идея:
    </p>

    <pre>
Файл поставщика
        ↓
Парсер
        ↓
Исходные данные
        ↓
Конфигурация поставщика
        ↓
ProductNormalizer
        ↓
Единая структура товара
        ↓
ProductImporter
        ↓
WooCommerce
    </pre>


