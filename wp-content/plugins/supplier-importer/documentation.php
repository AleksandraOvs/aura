    <h2 id="images">16. Изображения</h2>

    <p>
        Изображения сначала собираются ProductNormalizer
        в массив URL:
    </p>

    <pre>
[
    'https://example.com/image1.jpg',
    'https://example.com/image2.jpg',
]
    </pre>

    <p>
        Затем ProductImporter передаёт их ImageImporter.
    </p>

    <h3>Первый импорт</h3>

    <pre>
URL
 ↓
download_url()
 ↓
media_handle_sideload()
 ↓
WordPress attachment
    </pre>

    <h3>Повторный импорт</h3>

    <p>
        Для каждого изображения проверяется meta:
    </p>

    <pre>
_supplier_image_url
    </pre>

    <p>
        Если такое изображение уже импортировано для данного товара,
        оно пропускается.
    </p>

    <pre>
imported = 0
skipped = количество уже существующих изображений
failed = 0
    </pre>

    <p>
        Первое найденное изображение используется как главное,
        остальные — как изображения галереи.
    </p>


    <!-- =====================================================
         17. META
    ====================================================== -->

    <hr>

    <h2 id="supplier-meta">17. Данные поставщика и meta</h2>


    <p>
        Дополнительные данные поставщика не смешиваются
        с основными полями WooCommerce.
    </p>

    <p>
        Они сохраняются с префиксом:
    </p>

    <pre>
_supplier_
    </pre>

    <p>
        Например:
    </p>

    <pre>
_supplier_barcode
_supplier_brand
_supplier_source_url
_supplier_weight
_supplier_box_weight
_supplier_tn_ved
    </pre>

    <p>
        Это позволяет хранить исходные данные поставщика
        отдельно от стандартных данных WooCommerce.
    </p>


    <!-- =====================================================
         18. ПОВТОРНЫЙ ИМПОРТ
    ====================================================== -->

    <hr>

    <h2 id="repeat-import">18. Повторный импорт</h2>

    <p>
        Импорт рассчитан на регулярный запуск одного и того же файла.
    </p>

    <p>
        Первый запуск:
    </p>

    <pre>
товар не найден
→ создан
→ изображения скачаны
    </pre>

    <p>
        Второй запуск:
    </p>

    <pre>
товар найден
→ обновлён
→ существующие изображения пропущены
    </pre>

    <p>
        Повторный импорт не должен создавать дубликаты товаров.
    </p>


