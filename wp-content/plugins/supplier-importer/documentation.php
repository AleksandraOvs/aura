    <hr>

    <h2 id="empty-values">13. Пустые значения</h2>

    <p>
        ValueCleaner преобразует различные обозначения
        отсутствующего значения в <code>null</code>.
    </p>

    <p>
        Например:
    </p>

    <pre>
&lt;Пустое значение&gt;
пустое значение
отсутствует
нет данных
не указано
-
пустая строка
    </pre>

    <p>
        При нормализации такие значения превращаются в:
    </p>

    <pre>
null
    </pre>

    <p>
        Для импортёра <code>null</code> означает:
        поставщик не передал значение.
    </p>

    <p>
        Важное правило:
    </p>

    <pre>
null ≠ 0
    </pre>

    <p>
        Поэтому отсутствие цены не означает цену 0,
        а отсутствие остатка не означает остаток 0.
    </p>


